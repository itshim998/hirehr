import subprocess
import time
import http.server
import socketserver
import threading
import json
import os

class QuietHandler(http.server.SimpleHTTPRequestHandler):
    def log_message(self, format, *args):
        pass

def run():
    port = 8089
    server = http.server.ThreadingHTTPServer(("127.0.0.1", port), QuietHandler)
    t = threading.Thread(target=server.serve_forever, daemon=True)
    t.start()
    print(f"Server started on port {port}")

    targets = [
        ("home", f"http://127.0.0.1:{port}/index.html", "docs/lighthouse_home.json"),
        ("about", f"http://127.0.0.1:{port}/about-us/index.html", "docs/lighthouse_about.json")
    ]

    results = {}
    failures_by_target = {}

    try:
        for name, url, out_path in targets:
            print(f"Running Lighthouse for {name} ({url})...")
            cmd = [
                "npx.cmd",
                "lighthouse",
                url,
                "--output=json",
                f"--output-path={out_path}",
                "--chrome-flags=--headless=new --no-sandbox --disable-gpu",
                "--only-categories=performance,accessibility,best-practices,seo",
                "--form-factor=mobile",
                "--throttling.rttMs=40",
                "--throttling.throughputKbps=10240",
                "--throttling.cpuSlowdownMultiplier=1",
                "--quiet"
            ]
            res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
            if os.path.exists(out_path):
                with open(out_path, "r", encoding="utf-8") as f:
                    data = json.load(f)
                cats = data.get("categories", {})
                scores = {
                    "performance": int((cats.get("performance", {}).get("score") or 0) * 100),
                    "accessibility": int((cats.get("accessibility", {}).get("score") or 0) * 100),
                    "best-practices": int((cats.get("best-practices", {}).get("score") or 0) * 100),
                    "seo": int((cats.get("seo", {}).get("score") or 0) * 100)
                }
                results[name] = scores
                print(f"  {name} scores: {scores}")

                # Extract failing audits
                audits = data.get("audits", {})
                target_failures = []
                for cat_id, cat_data in cats.items():
                    for ref in cat_data.get("auditRefs", []):
                        audit_id = ref.get("id")
                        audit = audits.get(audit_id, {})
                        score = audit.get("score")
                        mode = audit.get("scoreDisplayMode")
                        if score is not None and score < 1 and mode not in ("notApplicable", "manual", "informative"):
                            # Collect offending elements / snippets
                            snippets = []
                            items = audit.get("details", {}).get("items", [])
                            for it in items:
                                if isinstance(it, dict):
                                    if "node" in it and isinstance(it["node"], dict):
                                        snip = it["node"].get("snippet") or it["node"].get("nodeLabel") or it["node"].get("selector")
                                        if snip:
                                            snippets.append(snip)
                                    elif "snippet" in it:
                                        snippets.append(it["snippet"])
                                    elif "url" in it:
                                        snippets.append(it["url"])
                                    elif "source" in it:
                                        snippets.append(str(it["source"]))

                            target_failures.append({
                                "category": cat_id,
                                "id": audit_id,
                                "title": audit.get("title", audit_id),
                                "description": audit.get("description", ""),
                                "snippets": snippets[:10]  # cap snippets for readability
                            })
                failures_by_target[name] = target_failures
            else:
                print(f"  Failed for {name}: {res.stderr}")
    finally:
        server.shutdown()

    # Write summary json
    with open("docs/lighthouse_summary.json", "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)

    # Write failing audits markdown report
    md_lines = ["# Lighthouse Audit Failures Report\n", f"Generated by `tools/run_lighthouse.py`.\n"]
    for name, fails in failures_by_target.items():
        score_info = results.get(name, {})
        md_lines.append(f"## Target: `{name}` (Scores: Perf={score_info.get('performance')}, A11y={score_info.get('accessibility')}, BP={score_info.get('best-practices')}, SEO={score_info.get('seo')})\n")
        if not fails:
            md_lines.append("No failing audits detected! 100% compliant across all categories.\n")
        else:
            for f in fails:
                md_lines.append(f"### `[{f['category'].upper()}]` {f['id']}: {f['title']}")
                if f['snippets']:
                    md_lines.append("**Offending Elements / Snippets:**")
                    for snip in f['snippets']:
                        md_lines.append(f"```html\n{snip}\n```")
                md_lines.append("")

    with open("docs/lighthouse_failures.md", "w", encoding="utf-8") as f:
        f.write("\n".join(md_lines))

    print("Lighthouse run complete. Report saved to docs/lighthouse_failures.md")

if __name__ == "__main__":
    run()
